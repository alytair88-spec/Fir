export const DICTIONARIES: Record<Lang, Dictionary> = { uk, hu, en };

export function translate(lang: Lang, key: TranslationKey, params?: Record<string, string | number>): string {
  let text = DICTIONARIES[lang][key] ?? uk[key];
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replace(`{${name}}`, String(value));
    }
  }
  return text;
}

export function isLang(value: unknown): value is Lang {
  return value === 'uk' || value === 'hu' || value === 'en';
}
